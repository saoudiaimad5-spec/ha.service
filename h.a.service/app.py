def init_db():
    with connect() as db:

        db.execute("""
     CREATE TABLE IF NOT EXISTS orders (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                created_at TEXT NOT NULL,
                customer_name TEXT NOT NULL,
                phone TEXT NOT NULL,
                email TEXT,
                category TEXT NOT NULL,
                service TEXT NOT NULL,
                details TEXT NOT NULL,
                quantity TEXT,
                deadline TEXT,
                delivery TEXT NOT NULL,
                payment TEXT NOT NULL,
                status TEXT NOT NULL DEFAULT 'جديد',
                notes TEXT DEFAULT '',
                filename TEXT DEFAULT '',
                payment_status TEXT DEFAULT 'غير مدفوع'
            )
        """)

        # إضافة السعر إلى جدول الطلبات الموجود إن لم يكن العمود موجودًا.
        db.execute("""
            ALTER TABLE orders
            ADD COLUMN IF NOT EXISTS total_price
            NUMERIC(12, 2) NOT NULL DEFAULT 0
        """)

        db.execute("""
            CREATE TABLE IF NOT EXISTS admin_users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT UNIQUE NOT NULL,
                password_hash TEXT NOT NULL
            )
        """)

        # قائمة أسعار الخدمات التي يديرها المدير. لا تمس الطلبات الحالية.
        db.execute("""
            CREATE TABLE IF NOT EXISTS service_prices (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                service_name TEXT UNIQUE NOT NULL,
                price NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (price >= 0),
                updated_at TEXT NOT NULL
            )
        """)

        # سجل الدفعات الجزئية والكاملة.
        db.execute("""
            CREATE TABLE IF NOT EXISTS order_payments (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                order_id BIGINT NOT NULL
                    REFERENCES orders(id) ON DELETE CASCADE,
                amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
                paid_at TEXT NOT NULL,
                method TEXT NOT NULL DEFAULT 'نقدًا',
                notes TEXT DEFAULT ''
            )
        """)

        # الحفاظ على حسابات المدير الحالية دون تغيير الاسم أو كلمة المرور.
        # لا يُنشأ حساب جديد إلا إذا كان جدول المديرين فارغًا.
        admin_count = db.execute(
            "SELECT COUNT(*) AS count FROM admin_users"
        ).fetchone()["count"]

        admin_password = os.environ.get("HA_ADMIN_PASSWORD")
        reset_requested = os.environ.get("HA_RESET_ADMIN_PASSWORD") == "1"

        if admin_count == 0:
            if not admin_password:
                raise RuntimeError(
                    "لا يوجد حساب مدير. أضف HA_ADMIN_PASSWORD في Render "
                    "لإنشاء الحساب الأول فقط."
                )
            db.execute(
                "INSERT INTO admin_users (username, password_hash) VALUES (%s, %s)",
                (os.environ.get("HA_ADMIN_USERNAME", "aimad"),
                 generate_password_hash(admin_password)),
            )
        elif reset_requested and admin_password:
            # إعادة التعيين لا تحدث إلا بطلب صريح عبر HA_RESET_ADMIN_PASSWORD=1.
            # لا تغيّر اسم المستخدم ولا تلمس الحسابات الأخرى.
            username_to_reset = os.environ.get("HA_ADMIN_USERNAME", "aimad")
            existing = db.execute(
                "SELECT id FROM admin_users WHERE username = %s",
                (username_to_reset,),
            ).fetchone()
            if existing:
                db.execute(
                    "UPDATE admin_users SET password_hash = %s WHERE id = %s",
                    (generate_password_hash(admin_password), existing["id"]),
                )


