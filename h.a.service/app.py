@app.route("/admin/order/<int:order_id>/price", methods=["POST"])
@admin_required
def update_order_price(order_id):
    raw_price = request.form.get("total_price", "").strip()

    try:
        price = Decimal(raw_price)

        if (
            not price.is_finite()
            or price < 0
            or price > Decimal("9999999999.99")
        ):
            raise InvalidOperation

        price = price.quantize(
            Decimal("0.01"),
            rounding=ROUND_HALF_UP,
        )

    except (InvalidOperation, ValueError):
        flash("السعر غير صحيح.", "error")
        return redirect(url_for("admin_dashboard"))

    with connect() as db:
        result = db.execute(
            """
            UPDATE orders
            SET total_price = %s
            WHERE id = %s
            RETURNING id
            """,
            (price, order_id),
        ).fetchone()

    if not result:
        abort(404)

    flash(
        f"تم تحديث سعر الطلب HA-{order_id:05d}.",
        "success",
    )

    return redirect(url_for("admin_dashboard"))


