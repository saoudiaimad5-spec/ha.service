@app.route("/admin/order/<int:order_id>/payments")
@admin_required
def order_payment_history(order_id):
    with connect() as db:
        order = db.execute(
            """
            SELECT id, total_price
            FROM orders
            WHERE id = %s
            """,
            (order_id,),
        ).fetchone()

        if not order:
            abort(404)

        payments = db.execute(
            """
            SELECT id, amount, paid_at, method, notes
            FROM order_payments
            WHERE order_id = %s
            ORDER BY id DESC
            """,
            (order_id,),
        ).fetchall()

        summary = get_payment_summary(db, order_id)

    return {
        "order_id": order_id,
        "total_price": str(summary["total_price"]),
        "amount_paid": str(summary["amount_paid"]),
        "remaining": str(summary["remaining"]),
        "payments": [
            {
                "id": payment["id"],
                "amount": str(payment["amount"]),
                "paid_at": payment["paid_at"],
                "method": payment["method"],
                "notes": payment["notes"],
            }
            for payment in payments
        ],
    }


