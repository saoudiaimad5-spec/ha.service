def connect():
    database_url = os.environ.get("DATABASE_URL")

    if not database_url:
        raise RuntimeError(
            "متغير DATABASE_URL غير موجود في إعدادات Render."
        )

    return psycopg.connect(
        database_url,
        row_factory=dict_row,
        connect_timeout=15,
    )


