def init_db():
    with connect() as db:
        
        db.execute("""
     CREATE TABLE IF NOT EXISTS orders (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                created_at TEXT NOT NULL,
                customer_name TEXT NOT NULL,
                phone TEXT NOT NULL,
                email TEXT,
                category TEXT NOT NULL,
                service TEXT NOT NULL,
                details TEXT NOT NULL,
                quantity TEXT,
                deadline TEXT,
                delivery TEXT NOT NULL,
                payment TEXT NOT NULL,
                status TEXT NOT NULL DEFAULT 'جديد',
                notes TEXT DEFAULT '',
                filename TEXT DEFAULT '',
                payment_status TEXT DEFAULT 'غير مدفوع'
            )
        """)

        # إضافة السعر إلى جدول الطلبات الموجود إن لم يكن العمود موجودًا.
        db.execute("""
            ALTER TABLE orders
            ADD COLUMN IF NOT EXISTS total_price
            NUMERIC(12, 2) NOT NULL DEFAULT 0
        """)

        db.execute("""
            CREATE TABLE IF NOT EXISTS admin_users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT UNIQUE NOT NULL,
                password_hash TEXT NOT NULL
            )
        """)

        # سجل الدفعات الجزئية والكاملة.
        db.execute("""
            CREATE TABLE IF NOT EXISTS order_payments (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                order_id BIGINT NOT NULL
                    REFERENCES orders(id) ON DELETE CASCADE,
                amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
                paid_at TEXT NOT NULL,
                method TEXT NOT NULL DEFAULT 'نقدًا',
                notes TEXT DEFAULT ''
            )
        """)

        # إعداد حساب المدير.
        admin_password = os.environ.get("HA_ADMIN_PASSWORD")
        reset_requested = (
            os.environ.get("HA_RESET_ADMIN_PASSWORD") == "1"
        )

        row = db.execute(
            "SELECT id FROM admin_users WHERE username = %s",
            ("aimad",),
        ).fetchone()

        # الحفاظ على الحساب القديم إن كان اسمه admin.
        if not row:
            old_admin = db.execute(
                "SELECT id FROM admin_users WHERE username = %s",
                ("admin",),
            ).fetchone()

            if old_admin:
                db.execute(
                    """
                    UPDATE admin_users
                    SET username = %s
                    WHERE id = %s
                    """,
                    ("aimad", old_admin["id"]),
                )
                row = {"id": old_admin["id"]}

        if admin_password:
            password_hash = generate_password_hash(admin_password)

            if row and reset_requested:
                db.execute(
                    """
                    UPDATE admin_users
                    SET password_hash = %s
                    WHERE id = %s
                    """,
                    (password_hash, row["id"]),
                )

            elif not row:
                db.execute(
                    """
                    INSERT INTO admin_users (username, password_hash)
                    VALUES (%s, %s)
                    """,
                    ("aimad", password_hash),
                )

        elif not row:
            raise RuntimeError(
                "حساب المدير غير موجود. أضف HA_ADMIN_PASSWORD "
                "في Environment على Render."
            )


