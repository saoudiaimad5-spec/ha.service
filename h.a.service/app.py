@app.route("/admin/order/<int:order_id>", methods=["POST"])
@admin_required
def update_order(order_id):
    status = request.form.get("status", "")
    notes = request.form.get("notes", "").strip()[:3000]

    if status not in STATUSES:
        abort(400)

    # لا نأخذ payment_status من النموذج؛ حالة الدفع تُحدّث عبر سجل الدفعات.
    with connect() as db:
        result = db.execute(
            """
            UPDATE orders
            SET status = %s,
                notes = %s
            WHERE id = %s
            RETURNING id
            """,
            (status, notes, order_id),
        ).fetchone()

    if not result:
        abort(404)

    flash(
        f"تم تحديث حالة الطلب وملاحظاته HA-{order_id:05d}. حالة الدفع لا تتغير من هذا النموذج.",
        "success",
    )

    return redirect(url_for("admin_dashboard"))


