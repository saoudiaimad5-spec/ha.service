def admin_required(fn):
    @wraps(fn)
    def wrapped(*args, **kwargs):
        if not session.get("admin_id"):
            return redirect(url_for("admin_login", next=request.path))
        return fn(*args, **kwargs)
    return wrapped


def allowed_file(filename):
    return (
        "." in filename
        and filename.rsplit(".", 1)[1].lower() in ALLOWED_EXTENSIONS
    )


def get_payment_summary(db, order_id):
    """حساب المدفوع والمتبقي لطلب واحد."""
    order = db.execute(
        "SELECT total_price FROM orders WHERE id = %s",
        (order_id,)
    ).fetchone()

    if not order:
        return None

    row = db.execute(
        """
        SELECT COALESCE(SUM(amount), 0) AS amount_paid
        FROM order_payments
        WHERE order_id = %s
        """,
        (order_id,)
    ).fetchone()

    total = Decimal(str(order["total_price"] or 0))
    paid = Decimal(str(row["amount_paid"] or 0))

    return {
        "total_price": total,
        "amount_paid": paid,
        "remaining": max(total - paid, Decimal("0.00"))
    }


