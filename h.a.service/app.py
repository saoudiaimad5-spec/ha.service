@app.route("/admin/delete/<int:order_id>", methods=["POST"])
@admin_required
def delete_order(order_id):
    with connect() as db:
        order = db.execute(
            "SELECT id FROM orders WHERE id = %s",
            (order_id,)
        ).fetchone()

        if not order:
            flash("الطلب غير موجود أو تم حذفه مسبقًا.", "error")
            return redirect(url_for("admin_dashboard"))

        db.execute(
            "DELETE FROM orders WHERE id = %s",
            (order_id,)
        )

    flash("تم حذف الطلب بنجاح.", "success")
    return redirect(url_for("admin_dashboard"))


@app.route("/admin/order/<int:order_id>", methods=["POST"])
@admin_required
def update_order(order_id):
    status = request.form.get("status", "")
    notes = request.form.get("notes", "").strip()[:3000]
    payment_status = request.form.get("payment_status", "غير مدفوع")

    if status not in STATUSES:
        abort(400)

    if payment_status not in PAYMENT_STATUSES:
        abort(400)

    with connect() as db:
        db.execute("""
            UPDATE orders
            SET status = %s, notes = %s, payment_status = %s
            WHERE id = %s
        """, (status, notes, payment_status, order_id))

    flash(f"تم تحديث الطلب HA-{order_id:05d}.", "success")
    return redirect(url_for("admin_dashboard"))


@app.route("/admin/file/<int:order_id>")
@admin_required
def download_order_file(order_id):
    with connect() as db:
        row = db.execute(
            "SELECT filename FROM orders WHERE id = %s",
            (order_id,)
        ).fetchone()

    if not row or not row["filename"]:
        abort(404)

    return send_from_directory(
        UPLOAD_DIR,
        row["filename"],
        as_attachment=True
    )


