@app.route("/admin")
@admin_required
def admin_dashboard():
    q = request.args.get("q", "").strip()
    status = request.args.get("status", "").strip()

    with connect() as db:
        totals = {
            "all": db.execute(
                "SELECT COUNT(*) AS count FROM orders"
            ).fetchone()["count"],

            "new": db.execute(
                "SELECT COUNT(*) AS count FROM orders WHERE status = %s",
                ("جديد",),
            ).fetchone()["count"],

            "progress": db.execute(
                "SELECT COUNT(*) AS count FROM orders WHERE status = %s",
                ("قيد الإنجاز",),
            ).fetchone()["count"],

            "ready": db.execute(
                "SELECT COUNT(*) AS count FROM orders WHERE status = %s",
                ("جاهز للاستلام",),
            ).fetchone()["count"],

            "paid": db.execute(
                """
                SELECT COUNT(*) AS count
                FROM orders
                WHERE payment_status IN (%s, %s)
                """,
                ("مدفوع في المكتب", "مدفوع إلكترونيًا"),
            ).fetchone()["count"],

            "pending_payment": db.execute(
                """
                SELECT COUNT(*) AS count
                FROM orders
                WHERE payment_status = %s
                """,
                ("بانتظار الدفع",),
            ).fetchone()["count"],

            "unpaid": db.execute(
                """
                SELECT COUNT(*) AS count
                FROM orders
                WHERE payment_status = %s
                """,
                ("غير مدفوع",),
            ).fetchone()["count"],

            "completed": db.execute(
                "SELECT COUNT(*) AS count FROM orders WHERE status = %s",
                ("تم التسليم",),
            ).fetchone()["count"],
        }

        financial = db.execute(
            """
            SELECT
                COALESCE(SUM(total_price), 0) AS total_value
            FROM orders
            """
        ).fetchone()

        received = db.execute(
            """
            SELECT COALESCE(SUM(amount), 0) AS total_received
            FROM order_payments
            """
        ).fetchone()

        total_value = Decimal(str(financial["total_value"] or 0))
        total_received = Decimal(str(received["total_received"] or 0))

        totals["total_value"] = total_value
        totals["total_received"] = total_received
        totals["total_remaining"] = max(
            total_value - total_received,
            Decimal("0.00"),
        )

        sql = "SELECT * FROM orders WHERE 1=1"
        args = []

        if q:
            order_number = q.upper().removeprefix("HA-").lstrip("0")
            if not order_number:
                order_number = "0"

            sql += """
                AND (
                    customer_name LIKE %s
                    OR phone LIKE %s
                    OR service LIKE %s
                    OR CAST(id AS TEXT) = %s
                )
            """

            args.extend([
                f"%{q}%",
                f"%{q}%",
                f"%{q}%",
                order_number,
            ])

        if status in STATUSES:
            sql += " AND status = %s"
            args.append(status)

        sql += " ORDER BY id DESC LIMIT 300"

        orders = db.execute(sql, args).fetchall()

        for order in orders:
            summary = get_payment_summary(db, order["id"])
            order["amount_paid"] = summary["amount_paid"]
            order["remaining"] = summary["remaining"]
            order["payments"] = db.execute(
                """SELECT id, amount, paid_at, method, notes
                   FROM order_payments WHERE order_id = %s ORDER BY id DESC""",
                (order["id"],),
            ).fetchall()

        service_prices = db.execute(
            "SELECT id, service_name, price, updated_at FROM service_prices ORDER BY service_name"
        ).fetchall()

    return render_template(
        "admin.html",
        orders=orders,
        totals=totals,
        q=q,
        selected_status=status,
        statuses=STATUSES,
        service_prices=service_prices,
        payment_methods=PAYMENT_METHODS,
    )


