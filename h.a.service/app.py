@app.route("/order", methods=["POST"])
def create_order():
    fields = [
        "customer_name", "phone", "email", "category", "service",
        "details", "quantity", "deadline", "delivery", "payment"
    ]

    data = {
        field: request.form.get(field, "").strip()
        for field in fields
    }

    required = [
        "customer_name", "phone", "category", "service",
        "details", "delivery", "payment"
    ]

    if any(not data[field] for field in required) or not request.form.get("consent"):
        flash(
            "يرجى ملء الحقول المطلوبة والموافقة على معالجة الطلب.",
            "error"
        )
        return redirect(url_for("index") + "#request")

    upload = request.files.get("attachment")
    stored_name = ""

    if upload and upload.filename:
        if not allowed_file(upload.filename):
            flash(
                "نوع الملف غير مسموح. استخدم PDF أو DOCX أو صورة أو ملفًا مدعومًا.",
                "error"
            )
            return redirect(url_for("index") + "#request")

        stored_name = (
            secrets.token_hex(16) + "_"
            + secure_filename(upload.filename)
        )
        upload.save(os.path.join(UPLOAD_DIR, stored_name))

    with connect() as db:
        row = db.execute("""
            INSERT INTO orders (
                created_at, customer_name, phone, email,
                category, service, details, quantity, deadline,
                delivery, payment, filename
            )
            VALUES (
                %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s
            )
            RETURNING id
        """, (
            datetime.now().isoformat(timespec="minutes"),
            data["customer_name"],
            data["phone"],
            data["email"],
            data["category"],
            data["service"],
            data["details"],
            data["quantity"],
            data["deadline"],
            data["delivery"],
            data["payment"],
            stored_name
        )).fetchone()

        order_id = row["id"]

    flash(
        f"تم تسجيل طلبك بنجاح. رقم الطلب: HA-{order_id:05d}. "
        "سيتواصل معك المكتب لتأكيد السعر والمدة.",
        "success"
    )
    return redirect(url_for("index") + "#request")


@app.route("/admin/login", methods=["GET", "POST"])
def admin_login():
    if request.method == "POST":
        username = request.form.get("username", "").strip()
        password = request.form.get("password", "")

        with connect() as db:
            user = db.execute(
                "SELECT * FROM admin_users WHERE username = %s",
                (username,)
            ).fetchone()

        if user and check_password_hash(user["password_hash"], password):
            session.clear()
            session["admin_id"] = user["id"]
            session["admin_name"] = user["username"]
            return redirect(url_for("admin_dashboard"))

        flash("اسم المستخدم أو كلمة المرور غير صحيحة.", "error")

    return render_template("login.html")


