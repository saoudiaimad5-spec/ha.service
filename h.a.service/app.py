@app.route("/admin")
@admin_required
def admin_dashboard():
    q = request.args.get("q", "").strip()
    status = request.args.get("status", "").strip()

    with connect() as db:
        totals = {
            "all": db.execute(
                "SELECT COUNT(*) AS count FROM orders"
            ).fetchone()["count"],

            "new": db.execute(
                "SELECT COUNT(*) AS count FROM orders WHERE status = %s",
                ("جديد",)
            ).fetchone()["count"],

            "progress": db.execute(
                "SELECT COUNT(*) AS count FROM orders WHERE status = %s",
                ("قيد الإنجاز",)
            ).fetchone()["count"],

            "ready": db.execute(
                "SELECT COUNT(*) AS count FROM orders WHERE status = %s",
                ("جاهز للاستلام",)
            ).fetchone()["count"],

            "paid": db.execute(
                """SELECT COUNT(*) AS count FROM orders
                   WHERE payment_status IN (%s, %s)""",
                ("مدفوع في المكتب", "مدفوع إلكترونيًا")
            ).fetchone()["count"],

            "pending_payment": db.execute(
                "SELECT COUNT(*) AS count FROM orders WHERE payment_status = %s",
                ("بانتظار الدفع",)
            ).fetchone()["count"],

            "unpaid": db.execute(
                "SELECT COUNT(*) AS count FROM orders WHERE payment_status = %s",
                ("غير مدفوع",)
            ).fetchone()["count"],

            "completed": db.execute(
                "SELECT COUNT(*) AS count FROM orders WHERE status = %s",
                ("تم التسليم",)
            ).fetchone()["count"]
        }

        financial = db.execute("""
            SELECT
                COALESCE(SUM(o.total_price), 0) AS total_value,
                COALESCE((
                    SELECT SUM(p.amount)
                    FROM order_payments p
                ), 0) AS total_received
            FROM orders o
        """).fetchone()

        totals["total_value"] = financial["total_value"]
        totals["total_received"] = financial["total_received"]
        totals["total_remaining"] = max(
            Decimal(str(financial["total_value"]))
            - Decimal(str(financial["total_received"])),
            Decimal("0.00")
        )

        sql = "SELECT * FROM orders WHERE 1=1"
        args = []

        if q:
            order_number = q.upper().removeprefix("HA-").lstrip("0")
            if not order_number:
                order_number = "0"

            sql += """
                AND (
                    customer_name LIKE %s
                    OR phone LIKE %s
                    OR service LIKE %s
                    OR CAST(id AS TEXT) = %s
                )
            """
            args.extend([
                f"%{q}%",
                f"%{q}%",
                f"%{q}%",
                order_number
            ])

        if status in STATUSES:
            sql += " AND status = %s"
            args.append(status)

        sql += " ORDER BY id DESC LIMIT 300"
        orders = db.execute(sql, args).fetchall()

        # إرفاق ملخص مالي بكل طلب دون تعديل بيانات الطلب.
        for order in orders:
            summary = get_payment_summary(db, order["id"])
            order["amount_paid"] = summary["amount_paid"]
            order["remaining"] = summary["remaining"]

    return render_template(
        "admin.html",
        orders=orders,
        totals=totals,
        q=q,
        selected_status=status,
        statuses=STATUSES
    )


@app.route("/admin/order/<int:order_id>/price", methods=["POST"])
@admin_required
def update_order_price(order_id):
    """تحديد السعر الإجمالي للطلب."""
    raw_price = request.form.get("total_price", "").strip()

    try:
        price = Decimal(raw_price)
        if not price.is_finite() or price < 0 or price > Decimal("9999999999.99"):
            raise InvalidOperation
        price = price.quantize(Decimal("0.01"))
    except (InvalidOperation, ValueError):
        flash("السعر غير صحيح. أدخل مبلغًا موجبًا وصحيحًا.", "error")
        return redirect(url_for("admin_dashboard"))

    with connect() as db:
        result = db.execute(
            "UPDATE orders SET total_price = %s WHERE id = %s RETURNING id",
            (price, order_id)
        ).fetchone()

    if not result:
        abort(404)

    flash(f"تم تحديث سعر الطلب HA-{order_id:05d}.", "success")
    return redirect(url_for("admin_dashboard"))


@app.route("/admin/order/<int:order_id>/payment", methods=["POST"])
@admin_required
def add_order_payment(order_id):
    """تسجيل دفعة جزئية أو كاملة للطلب."""
    raw_amount = request.form.get("amount", "").strip()
    method = request.form.get("method", "نقدًا").strip()
    notes = request.form.get("payment_notes", "").strip()[:1000]

    if method not in PAYMENT_METHODS:
        abort(400)

    try:
        amount = Decimal(raw_amount)
        if (
            not amount.is_finite()
            or amount <= 0
            or amount > Decimal("9999999999.99")
        ):
            raise InvalidOperation
        amount = amount.quantize(Decimal("0.01"))
    except (InvalidOperation, ValueError):
        flash("مبلغ الدفعة غير صحيح.", "error")
        return redirect(url_for("admin_dashboard"))

    with connect() as db:
        order = db.execute(
            "SELECT id, total_price FROM orders WHERE id = %s FOR UPDATE",
            (order_id,)
        ).fetchone()

        if not order:
            abort(404)

        summary = get_payment_summary(db, order_id)
        if amount > summary["remaining"]:
            flash(
                "مبلغ الدفعة أكبر من المبلغ المتبقي. راجع سعر الطلب والدفعات السابقة.",
                "error"
            )
            return redirect(url_for("admin_dashboard"))

        db.execute("""
            INSERT INTO order_payments (
                order_id, amount, paid_at, method, notes
            )
            VALUES (%s, %s, %s, %s, %s)
        """, (
            order_id,
            amount,
            datetime.now().isoformat(timespec="seconds"),
            method,
            notes
        ))

        new_summary = get_payment_summary(db, order_id)

        if new_summary["amount_paid"] == 0:
            new_status = "غير مدفوع"
        elif new_summary["remaining"] > 0:
            new_status = "بانتظار الدفع"
        else:
            new_status = (
                "مدفوع إلكترونيًا" if method != "نقدًا"
                else "مدفوع في المكتب"
            )

        db.execute(
            "UPDATE orders SET payment_status = %s WHERE id = %s",
            (new_status, order_id)
        )

    flash(f"تم تسجيل الدفعة للطلب HA-{order_id:05d}.", "success")
    return redirect(url_for("admin_dashboard"))


@app.route("/admin/order/<int:order_id>/payments")
@admin_required
def order_payment_history(order_id):
    """عرض سجل الدفعات بصيغة JSON للمدير المسجل."""
    with connect() as db:
        order = db.execute(
            "SELECT id, total_price FROM orders WHERE id = %s",
            (order_id,)
        ).fetchone()

        if not order:
            abort(404)

        payments = db.execute("""
            SELECT id, amount, paid_at, method, notes
            FROM order_payments
            WHERE order_id = %s
            ORDER BY id DESC
        """, (order_id,)).fetchall()

        summary = get_payment_summary(db, order_id)

    return {
        "order_id": order_id,
        "total_price": str(summary["total_price"]),
        "amount_paid": str(summary["amount_paid"]),
        "remaining": str(summary["remaining"]),
        "payments": [
            {
                "id": p["id"],
                "amount": str(p["amount"]),
                "paid_at": p["paid_at"],
                "method": p["method"],
                "notes": p["notes"]
            }
            for p in payments
        ]
    }


