@app.route("/admin/file/<int:order_id>")
@admin_required
def download_order_file(order_id):
    with connect() as db:
        row = db.execute(
            """
            SELECT filename
            FROM orders
            WHERE id = %s
            """,
            (order_id,),
        ).fetchone()

    if not row or not row["filename"]:
        abort(404)

    return send_from_directory(
        UPLOAD_DIR,
        row["filename"],
        as_attachment=True,
    )


