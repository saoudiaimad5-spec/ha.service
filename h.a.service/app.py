@app.route("/admin/service-prices", methods=["POST"])
@admin_required
def save_service_price():
    service_name = request.form.get("service_name", "").strip()[:160]
    raw_price = request.form.get("service_price", "").strip()
    service_id = request.form.get("service_id", "").strip()
    if not service_name:
        flash("أدخل اسم الخدمة.", "error")
        return redirect(url_for("admin_dashboard") + "#service-prices")
    try:
        price = Decimal(raw_price)
        if not price.is_finite() or price < 0 or price > Decimal("9999999999.99"):
            raise InvalidOperation
        price = price.quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)
    except (InvalidOperation, ValueError):
        flash("سعر الخدمة غير صحيح.", "error")
        return redirect(url_for("admin_dashboard") + "#service-prices")
    with connect() as db:
        if service_id:
            try:
                sid = int(service_id)
            except ValueError:
                abort(400)
            conflict = db.execute("SELECT id FROM service_prices WHERE service_name = %s AND id <> %s", (service_name, sid)).fetchone()
            if conflict:
                flash("اسم الخدمة موجود بالفعل.", "error")
            else:
                result = db.execute("UPDATE service_prices SET service_name = %s, price = %s, updated_at = %s WHERE id = %s RETURNING id", (service_name, price, datetime.now().isoformat(timespec="seconds"), sid)).fetchone()
                if not result:
                    abort(404)
                flash("تم تعديل سعر الخدمة.", "success")
        else:
            conflict = db.execute(
                "SELECT id FROM service_prices WHERE service_name = %s",
                (service_name,),
            ).fetchone()
            if conflict:
                flash("اسم الخدمة موجود بالفعل. عدّل الخدمة الموجودة بدلًا من تكرارها.", "error")
            else:
                db.execute(
                    "INSERT INTO service_prices (service_name, price, updated_at) VALUES (%s, %s, %s)",
                    (service_name, price, datetime.now().isoformat(timespec="seconds")),
                )
                flash("تمت إضافة الخدمة إلى قائمة الأسعار.", "success")
    return redirect(url_for("admin_dashboard") + "#service-prices")


