@app.route("/order", methods=["POST"])
def create_order():
    fields = [
        "customer_name",
        "phone",
        "email",
        "category",
        "service",
        "details",
        "quantity",
        "deadline",
        "delivery",
        "payment",
    ]

    data = {
        field: request.form.get(field, "").strip()
        for field in fields
    }

    required = [
        "customer_name",
        "phone",
        "category",
        "service",
        "details",
        "delivery",
        "payment",
    ]

    if (
        any(not data[field] for field in required)
        or not request.form.get("consent")
    ):
        flash(
            "يرجى ملء الحقول المطلوبة والموافقة على معالجة الطلب.",
            "error",
        )
        return redirect(url_for("index") + "#request")

    upload = request.files.get("attachment")
    stored_name = ""

    if upload and upload.filename:
        if not allowed_file(upload.filename):
            flash(
                "نوع الملف غير مسموح. استخدم نوعًا مدعومًا.",
                "error",
            )
            return redirect(url_for("index") + "#request")

        stored_name = (
            secrets.token_hex(16)
            + "_"
            + secure_filename(upload.filename)
        )

        upload.save(os.path.join(UPLOAD_DIR, stored_name))

    with connect() as db:
        row = db.execute(
            """
            INSERT INTO orders (
                created_at,
                customer_name,
                phone,
                email,
                category,
                service,
                details,
                quantity,
                deadline,
                delivery,
                payment,
                filename
            )
            VALUES (
                %s, %s, %s, %s, %s, %s,
                %s, %s, %s, %s, %s, %s
            )
            RETURNING id
            """,
            (
                datetime.now().isoformat(timespec="minutes"),
                data["customer_name"],
                data["phone"],
                data["email"],
                data["category"],
                data["service"],
                data["details"],
                data["quantity"],
                data["deadline"],
                data["delivery"],
                data["payment"],
                stored_name,
            ),
        ).fetchone()

        order_id = row["id"]

    flash(
        f"تم تسجيل طلبك بنجاح. رقم الطلب: HA-{order_id:05d}. "
        "سيتواصل معك المكتب لتأكيد السعر والمدة.",
        "success",
    )

    return redirect(url_for("index") + "#request")


